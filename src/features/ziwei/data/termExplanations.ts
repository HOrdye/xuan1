/**
 * 获取术语解释
 * @param term 术语名称
 * @param mode 模式：'simple' | 'professional'
 */
export function getTermExplanation(term: string, mode: 'simple' | 'professional' = 'simple'): string | null {
  const explanation = TERM_EXPLANATIONS[term];
  if (!explanation) {
    return null;
  }
  return explanation[mode];
}

/**
 * 检查术语是否存在
 */
export function hasTermExplanation(term: string): boolean {
  return term in TERM_EXPLANATIONS;
}

/**
 * 获取所有术语分类
 */
export function getTermCategories(): string[] {
  const categories = new Set<string>();
  Object.values(TERM_EXPLANATIONS).forEach(exp => {
    categories.add(exp.category);
  });
  return Array.from(categories);
}

