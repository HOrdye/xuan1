/**
 * 紫微斗数术语数据库
 * 标准化数据结构，包含完整的术语解释信息
 * 用于术语解释系统和AI解读功能
 * 
 * 数据结构：
 * - name: 术语名称
 * - alias: 别名/俗称
 * - icon: emoji图标
 * - brief: 简要说明（一句话）
 * - description: 详细说明
 * - traits: 特质列表
 * - suitable: 适合的职业/场景
 * - attention: 注意事项
 * - stories: 故事化解释（通俗易懂）
 */

export interface TerminologyItem {
  name: string;
  alias: string;
  icon: string;
  brief: string;
  description: string;
  traits: string[];
  suitable: string[];
  attention: string[];
  stories?: string; // 故事化解释，让用户更容易理解
  related?: {
    type: keyof TerminologyData;
    names: string[];
  }; // 关联术语，用于格局关联星曜
  category?: '贵格' | '富格' | '刑格' | '变格' | '特殊格'; // 格局分类标识
  element?: string; // 五行属性：金、木、水、火、土
  yinyang?: string; // 阴阳属性：阴、阳
}

export interface TerminologyData {
  mainStars: Record<string, TerminologyItem>;
  luckyStars: Record<string, TerminologyItem>; // 六吉星
  malignantStars: Record<string, TerminologyItem>; // 六煞星
  sihua: Record<string, TerminologyItem>;
  palaces: Record<string, TerminologyItem>;
  patterns: Record<string, TerminologyItem>; // 格局
}

