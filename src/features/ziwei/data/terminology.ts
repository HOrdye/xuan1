/**
 * 完整的术语数据库
 */
export const TERMINOLOGY: TerminologyData = {
  mainStars: MAIN_STARS_TERMINOLOGY,
  luckyStars: AUXILIARY_STARS_TERMINOLOGY, // 六吉星
  malignantStars: MALIGNANT_STARS_TERMINOLOGY, // 六煞星
  sihua: SIHUA_TERMINOLOGY,
  palaces: PALACES_TERMINOLOGY,
  patterns: PATTERNS_TERMINOLOGY
};

/**
 * 根据类型和名称获取术语数据
 */
export function getTerminology(type: keyof TerminologyData, name: string): TerminologyItem | undefined {
  return TERMINOLOGY[type]?.[name];
}

/**
 * 搜索术语（支持名称和别名搜索，带权重排序）
 * 
 * 权重规则：
 * - 完全匹配名称：10分
 * - 名称包含查询词：8分
 * - 别名匹配：6分
 * - 简介匹配：4分
 * - 描述匹配：2分
 * 
 * @param query 搜索关键词
 * @returns 按匹配度排序的搜索结果
 */
export function searchTerminology(query: string): Array<{
  type: keyof TerminologyData;
  name: string;
  item: TerminologyItem;
  score: number;
}> {
  const results: Array<{
    type: keyof TerminologyData;
    name: string;
    item: TerminologyItem;
    score: number;
  }> = [];
  const lowerQuery = query.toLowerCase();

  (Object.entries(TERMINOLOGY) as Array<[keyof TerminologyData, Record<string, TerminologyItem>]>).forEach(([type, items]) => {
    Object.entries(items).forEach(([name, item]) => {
      let score = 0;
      
      // 完全匹配名称：10分
      if (name.toLowerCase() === lowerQuery) {
        score += 10;
      }
      // 名称包含查询词：8分
      else if (name.toLowerCase().includes(lowerQuery)) {
        score += 8;
      }
      
      // 别名匹配：6分
      if (item.alias.toLowerCase().includes(lowerQuery)) {
        score += 6;
      }
      
      // 简介匹配：4分
      if (item.brief.toLowerCase().includes(lowerQuery)) {
        score += 4;
      }
      
      // 描述匹配：2分
      if (item.description.toLowerCase().includes(lowerQuery)) {
        score += 2;
      }

      if (score > 0) {
        results.push({ type, name, item, score });
      }
    });
  });

  // 按匹配度排序
  return results.sort((a, b) => b.score - a.score);
}

/**
 * 按特质筛选术语
 * 
 * @param trait 特质关键词
 * @returns 包含该特质的术语列表
 */
export function filterByTrait(trait: string): Array<{
  type: keyof TerminologyData;
  name: string;
  item: TerminologyItem;
}> {
  const results: Array<{
    type: keyof TerminologyData;
    name: string;
    item: TerminologyItem;
  }> = [];
  const lowerTrait = trait.toLowerCase();

  (Object.entries(TERMINOLOGY) as Array<[keyof TerminologyData, Record<string, TerminologyItem>]>).forEach(([type, items]) => {
    Object.entries(items).forEach(([name, item]) => {
      if (item.traits.some(t => t.toLowerCase().includes(lowerTrait))) {
        results.push({ type, name, item });
      }
    });
  });

  return results;
}

/**
 * 按类型筛选术语
 * 
 * @param type 术语类型
 * @returns 该类型下的所有术语列表
 */
export function filterByType(type: keyof TerminologyData): Array<{
  name: string;
  item: TerminologyItem;
}> {
  const items = TERMINOLOGY[type];
  if (!items) return [];

  return Object.entries(items).map(([name, item]) => ({
    name,
    item
  }));
}

