/**
 * 根据纳音获取五行局数
 */
export function getJuByNayin(nayin: string): number {
  return NAYIN_JU_MAP[nayin] || 2; // 默认水二局
}

/**
 * 根据五行局数获取名称
 */
export function getJuName(ju: number): string {
  return JU_TO_NAME[ju] || '水二局';
}

