/**
 * 根据年份获取甲子序号（1-60）
 */
export function getJiaziIndex(year: number): number {
  // 1984年为甲子年（序号1）
  const baseYear = 1984;
  const offset = (year - baseYear) % 60;
  return offset <= 0 ? offset + 60 : offset;
}

/**
 * 根据年份获取纳音
 */
export function getNayinByYear(year: number): string {
  const jiaziIndex = getJiaziIndex(year);
  return JIAZI_NAYIN[jiaziIndex] || '海中金';
}

